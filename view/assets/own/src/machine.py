def sheet():
    s = Sheet("machine.png", 8)
    s.add("fix.vending machine", pic(MACHINE))
    s.add("fix.vending machine.lit", pic(MACHINE, LIT))
    made = {n: m for n, m in draw.materials().items() if m.get("sheet") == "machine"}
    for name, m in made.items():
        like = BITS.get(m["like"]) or art.BITS[m["like"]]
        s.add("bit." + name, pic(BITS[name]) if name in BITS else draw.recoloured(pic(like), m["tint"]))
    return s


if __name__ == "__main__":
    own = {n: e for n, e in sheet().save().items() if not n.startswith("fix.vending machine")}   # (the machine itself is works.py's now: its old picture stays in the sheet so nothing moves)
    # sprites.json is kept by hand, one name to a line: this sheet's lines go in as one block right after "fix.bed"
    path = os.path.join(ASSETS, "sprites.json")
    lines = [l for l in open(path).read().split("\n") if not re.match(r' "(%s)":' % "|".join(re.escape(n) for n in own), l)]
    at = next(i for i, l in enumerate(lines) if l.startswith(' "fix.bed":'))
    lines[at + 1:at + 1] = [" %s: %s," % (json.dumps(n), json.dumps(e)) for n, e in own.items()]
    open(path, "w").write("\n".join(lines))
    print("drew %d pictures into own/machine.png" % len(own))
